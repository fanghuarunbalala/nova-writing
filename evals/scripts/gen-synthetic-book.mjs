	const pools = [
		FILLER_POOLS[chapterNo % FILLER_POOLS.length],
		FILLER_POOLS[(chapterNo + 1) % FILLER_POOLS.length],
		FILLER_POOLS[(chapterNo + 2) % FILLER_POOLS.length],
	];
	const out = [];
