        "- **节奏有呼吸**：长短句交替制造节奏，重大情绪落点、转折、冲击处用极短句成段制造停顿（例：“刀出鞘的时候，雨停了半拍。”）。",
        "- **每个场景结尾有钩子**：场景结束时，读者必须有一个未满足的期待——可以是悬念、可以是即将发生的冲突、可以是情感的悬而未决。",
        "",
        "## 什么不是好的正文",
