        "- **情绪先行标注**：先写情绪判断再给场景（例：“他内心一阵激动，颤抖着说……”）。情绪要靠动作、对话、物象让读者自己得出，标注情绪等于替读者阅读。",
        "- **信息重复**：同一信息在不同段落以不同措辞反复出现。（例：第三章已经交代过主角的身世，第七章又用回忆的方式完整复述一遍。）",
        "- **对话像说明文**：角色说话像在念设定集或百科词条。（例：“众所周知，我们天元大陆分为九大境界，分别是炼气、筑基、金丹……”——没有角色会在日常对话中这样说话。）",
