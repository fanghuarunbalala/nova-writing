        "- **对话引号不规范**：用英文直引号（\"...\"）、单引号或无引号写对白；或引号内夹多句对白又夹长叙述。",
        "- **大段环境描写或心理独白**：超过100字的纯环境描写或纯心理活动，且期间无任何事件发生。（例：花200字描写夕阳如何染红天际，主角站在山顶感慨人生。——读者会跳过。）",
